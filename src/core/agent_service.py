# 第 6 步：组装 Agent（分三个小函数拆开讲）
# ======================================================================
# 模块级单例：Streamlit 重跑脚本时复用，避免每轮对话都重新创建 Agent
_agent_executor = None


def create_llm():
    """功能：创建 DeepSeek 大模型对象
    入参：无（密钥、超时等全部来自 config.py / .env）
    返回：llm —— ChatDeepSeek 对象，可以 .invoke() 对话、.bind_tools() 挂工具
    使用场景：组装 Agent 的第 1 小步
    """
    llm = ChatDeepSeek(
        model=config.DEEPSEEK_MODEL,            # 必须 deepseek-chat，禁止 deepseek-reasoner
        api_key=config.DEEPSEEK_API_KEY,        # 密钥来自 .env，绝不硬编码
        api_base=config.DEEPSEEK_BASE_URL,      # 接口地址
        temperature=config.DEEPSEEK_TEMPERATURE, # 创作温度（.env 可调）：默认 0.9，越高越不容易"套路化"
        max_tokens=config.DEEPSEEK_MAX_TOKENS,  # 单次回复最大 token
        timeout=config.DEEPSEEK_TIMEOUT,        # 网络请求超时时间（秒）
        max_retries=config.DEEPSEEK_MAX_RETRIES,# 失败自动重试次数
    )
    return llm


def create_prompt():
    """功能：创建聊天式提示词模板（系统提示词 + 对话历史 + 用户输入 + 草稿区）
    入参：无
    返回：prompt —— ChatPromptTemplate 对象
    使用场景：组装 Agent 的第 2 小步
    """
    # ChatPromptTemplate.from_messages：按"消息角色"拼提示词（Day1 学的
    # system / user / assistant 三种角色，这里用得上）：
    #   ("system", ...)             —— 立规矩（系统提示词）
    #   ("human",  ...)             —— 用户消息（含对话历史和当前输入）
    #   MessagesPlaceholder(...)    —— 占位"草稿区"，Agent 中间的工具调用/返回
    #                                  会以消息列表的形式自动填进来
    prompt = ChatPromptTemplate.from_messages(
        [
            ("system", SYSTEM_PROMPT),
            ("human", REACT_PROMPT_TEMPLATE),
            MessagesPlaceholder("agent_scratchpad"),
        ]
    )
    return prompt


def create_agent_executor():
    """功能：组装完整的 ReAct Agent 执行器（大模型 + 提示词 + 工具）
    入参：无
    返回：executor —— AgentExecutor 对象，调用 .invoke() 就能对话
    使用场景：组装 Agent 的第 3 小步（也是最后一步）
    """
    # ---- 3.1 创建大模型 ----
    llm = create_llm()

    # ---- 3.2 创建提示词 ----
    prompt = create_prompt()

    # ---- 3.3 创建工具调用型 Agent ----
    # 【本课程核心知识点·function-call 原理】
    # create_tool_calling_agent 内部会调用 llm.bind_tools(TOOLS)：
    #   ① 把每个工具的"函数签名 + docstring"转成 JSON Schema 交给 DeepSeek；
    #   ② 模型觉得该用工具时，输出的不是普通文字，而是一段结构化的
    #      "我要调用 xxx 工具、参数是 yyy" 的调用请求（这就是 function-call）；
    #   ③ Python 真正执行工具函数，把结果作为消息回喂给模型继续思考；
    #   ④ 循环直到模型给出最终回答。
    # 一句话总结：大模型负责"决策"，Python 负责"执行"——模型永远不直接碰数据库。
    #
    # 【必考】必须用 deepseek-chat：它支持 function-call；
    # deepseek-reasoner(R1) 不支持，所以 config.py 里做了启动拦截。
    #
    # 【为什么不写 Thought/Action 文本格式】因为原生 function-call 不需要，
    # 模型直接给结构化调用；而文本式 ReAct（create_react_agent）无法处理
    # 多参数工具（会把整串 JSON 塞进第一个参数），详见第 5 步注释。
    agent = create_tool_calling_agent(
        llm=llm,
        tools=TOOLS,
        prompt=prompt,
    )

    # ---- 3.4 用 AgentExecutor 包一层执行器 ----
    # 【四个关键参数逐个讲（答辩高频）】
    #   verbose=True              ：终端打印完整思考过程，课堂演示神器
    #   handle_parsing_errors=True：模型输出格式异常时，自动把错误回喂给模型重试
    #   max_iterations=...        ：限制最多调 N 轮工具，防止模型陷入"死循环"
    #   return_intermediate_steps=True：返回每一步工具调用的输入输出，
    #                              供网页"工具调用日志"面板展示（教学观察核心）
    executor = AgentExecutor(
        agent=agent,
        tools=TOOLS,
        verbose=True,
        handle_parsing_errors=True,
        max_iterations=config.AGENT_MAX_ITERATIONS,
        return_intermediate_steps=True,
    )
    return executor


def get_agent_executor():
    """功能：获取 Agent 单例（懒加载：第一次对话时才真正创建）
    入参：无
    返回：executor —— AgentExecutor 对象
    使用场景：chat() 里调用；模块级缓存保证只创建一次
    """
    global _agent_executor
    if _agent_executor is None:
        _agent_executor = create_agent_executor()
    return _agent_executor


# ======================================================================
# 第 7 步：多轮对话记忆 —— 把历史对话拼成提示词文本
# ======================================================================
# 【记忆怎么讲】大模型本身没有记忆，每次请求都是"失忆"的。
# 多轮对话的真相：把历史对话文本带在提示词里。
# 但全带太贵（token 要花钱），所以只带最近 N 轮、AI 回答截断 500 字。
def format_history_text(rows, max_turns: int = None) -> str:
    """功能：把数据库查询到的对话记录拼接成提示词文本（只取最近 N 轮）
    入参：
        rows      —— DBUtil.get_chat_history() 返回的记录列表
        max_turns —— 最多带几轮历史（不传就用 config.MAX_HISTORY_TURNS）
    返回：拼接好的历史对话文本，例如：
          "用户：xxx\\n智能体：yyy\\n用户：aaa\\n智能体：bbb"
          没有历史时返回"（暂无历史对话）"
    使用场景：app.py 每轮对话前调用，实现"续写/改角色/改结局"
    """
    # 没传就用配置默认值
    if max_turns is None:
        max_turns = config.MAX_HISTORY_TURNS

    # 没有历史记录的情况
    if not rows:
        return "（暂无历史对话）"

    lines = []   # 先收集每一行，最后统一拼接
    for row in rows[-max_turns:]:            # 只取最近 N 轮（Day1 学的负索引切片）
        lines.append(f"用户：{row['user_query']}")
        # AI 回答可能很长，注入提示词时截断到 500 字，避免浪费 token（成本意识）
        lines.append(f"智能体：{row['ai_answer'][:500]}")
    return "\n".join(lines)


# ======================================================================
# 第 8 步：模糊需求识别（代码兜底，不依赖模型自觉）
# ======================================================================
# 【为什么要用代码兜底】
# "需求模糊时先追问"这条规则写在提示词里，但实测模型经常不听话：
# 输入"我要创作故事"时它直接就开写了（在它看来"创作故事"就是个明确指令）。
# 提示词约束是**概率性**的，关键行为用代码判定才是**确定性**的 ——
# 这正是本项目一路贯彻的"容错设计"思路（和网页端的故事补展示、补存档同一套哲学）。
#
# 【判定算法】把输入里的"意愿词 + 量词 + 故事名词 + 语气词 + 标点"全部剥掉，
# 剥完什么都不剩 → 用户只表达了"想听故事"这个意愿、没给任何具体内容 → 该追问。
#   例："写个故事"→空 ✓  "我要创作故事"→空 ✓  "帮我写一篇"→空 ✓
#       "我要创作一些故事"→空 ✓（"一些"要能剥干净，否则剩个"一"字就漏判了）
#       "「写个故事」"→空 ✓（全角引号也必须剥掉）
#       "写个关于分享的故事"→剩"关于分享" ✗ 不追问，直接创作
#       "写个小猪的故事"→剩"小猪" ✗ 不追问
# 【踩过的坑·一定要看】词表漏词 → 剥完还剩一两个字 → 被当成"有具体内容"，
#   判成明确需求 → 问卷根本不弹，用户看到的现象就是"点选功能坏了"。
#   实测漏过的三例："我要创作一些故事"（剩"一"）、"写个故事」"（剩"」"）、
#   "我想看故事"（剩"看"）。所以量词要收全（一些/一点/几个/几篇 + 单字 一/几/两），
#   动词要收"看"，标点要收全角。
# ----------------------------------------------------------------------
# 标点 / 空白字符类：剥词之前先要把这些"没有语义的符号"一起剥掉。
# 【为什么单独抽成常量】原来只写了半角几个标点，中文输入法打出的全角标点
# （「」《》""等）剥不掉，剥完还剩一个字符，于是整句被判成"有具体内容"。
# 抽成常量是为了让下面两张词表共用同一套符号，避免改一处、漏一处。
# ----------------------------------------------------------------------
