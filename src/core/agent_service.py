# ======================================================================
# 第 1 步：请求级上下文（会话ID / 本轮存档记录）
# ======================================================================
# 【这里原本是全局变量，为什么要改？—— 本项目一处真实并发缺陷的修复】
# 保存故事前要先知道"故事属于哪个会话"，最早的写法是模块级全局变量：
#     _current_session_id = ""
# 单用户单标签页时没事，但它埋着一个坑：
#     Streamlit 每开一个浏览器标签页 = 一个独立会话，可它们**共享同一个 Python 进程内存**。
#     两个标签页同时用时，A 刚写入的会话ID会被 B 覆盖 —— A 生成的故事就存进了 B 的会话，
#     页面上还可能冒出"别人的故事"。答辩现场开两个窗口对比演示，必然翻车。
#
# 【改成什么】contextvars.ContextVar —— Python 3.7+ 标准库自带的"请求级变量"。
#   它给每个执行上下文一份**独立副本**，相当于"每人一本自己的记事本"，
#   而不是"全公司共用一块白板"。
# 【答辩一句话】全局变量是共享白板，ContextVar 是各人记事本 —— 天然隔离，还不用加锁。
_current_session_id = contextvars.ContextVar("current_session_id", default="")

# 【一个曾经存在的变量：_last_saved_story】
# 早先这里放着一个 ContextVar，用来记住"最近一次成功保存的故事"。它要解决的问题是：
# 模型偶尔会偷懒 —— 把故事正文交给存档工具后，最终回答只写一句"已保存完成"，
# 页面上就看不到故事全文了，所以需要留一份正文给网页做兜底展示。
# 后来发现这个做法有两个毛病：
#   ① 脆弱：流式路径（astream_events）里工具跑在子任务的上下文副本中，
#      写进去的值外层读不到，兜底会**静默失效**；
#   ② 多余：正文其实**就在工具调用的参数里**，没必要再存一遍。
# 于是改成"需要时从工具调用参数里还原"（见 _story_from_tool_args）：
# 少一个状态、少一处隐患，同步与流式两个入口也能共用同一套逻辑。
# 【答辩一句话】能用"无状态重算"解决的，就别引入新状态。


def set_current_session(session_id: str):
    """功能：设置当前会话ID（写进本执行上下文的私有副本，不与其他标签页共享）
    入参：
        session_id —— 会话ID（字符串）
    返回：无
    使用场景：app.py / 自测脚本 在对话前调用，告诉工具"当前是谁在聊"
    """
    _current_session_id.set(session_id)


def get_current_session() -> str:
    """功能：读取当前会话ID
    入参：无
    返回：会话ID字符串（未设置时为空串）
    使用场景：工具2（保存故事）在存库前取它，作为故事的归属会话
    """
    return _current_session_id.get()


def reset_turn_context(session_id: str = ""):
    """功能：开始新一轮对话前，绑定本轮的会话ID
    入参：
        session_id —— 本轮会话ID（为空则沿用已设置的那个）
    返回：无
    使用场景：chat() / chat_stream() 每轮开头调用。线程被复用时不会读到上一轮的残留值。
    """
    if session_id:
        _current_session_id.set(session_id)


def _story_from_tool_args(args, observation):
    """功能：从"故事存档工具"的调用参数里还原这一轮存进库的那篇故事
    入参：
        args        —— 工具入参。可能是字典（同步路径），
                       也可能是它的字面量字符串（流式事件路径）
        observation —— 工具返回的文本，用来确认"确实存成功了"
    返回：
        字典 {"story_title", "main_role", "age_group", "story_content", "moral"}；
        不是一次成功的存档时返回 None
    使用场景：网页的"兜底展示" —— 模型最终回答里没复述正文时，把完整正文补到页面。
    """
    if isinstance(args, str):
        try:
            args = ast.literal_eval(args)        # 只解析字面量，不执行代码，安全
        except (ValueError, SyntaxError):
            return None
    if not isinstance(args, dict):
        return None
    if args.get("action") != "save":                 # 查询动作不产生故事
        return None
    if "已成功保存" not in str(observation or ""):    # 没真正存成功就不算数
        return None
    body = str(args.get("story_content", "") or "")
    if not body.strip():
        return None
    return {
        "story_title": str(args.get("story_title", "")).strip().strip("《》") or "未命名故事",
        "main_role": str(args.get("main_role", "")).strip() or "未指定",
        "age_group": str(args.get("age_group", "")).strip() or "未指定",
        "story_content": body,
        "moral": str(args.get("moral", "")).strip() or "未指定",
    }


def _find_saved_story(steps):
    """功能：从工具调用步骤里找出"本轮存进库的那篇故事"
    入参：steps —— [(AgentAction, observation), ...]（同步 invoke 与流式路径通用）
    返回：故事字典；本轮没有成功存档则返回 None
    """
    found = None
    for action, observation in steps or []:
        if getattr(action, "tool", "") == "story_db_tool":
            found = _story_from_tool_args(
                getattr(action, "tool_input", None), observation) or found
    return found


