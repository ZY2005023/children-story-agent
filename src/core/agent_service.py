"""
======================================================================
agent_service.py —— 智能体核心（新手入门第 4 课，全项目最重要的文件）
======================================================================

【什么是 Agent（智能体）？】
普通大模型只会"说话"；Agent = 大模型 + 工具 + 决策循环。
大模型自己判断"现在需要调用哪个工具"，工具执行真实动作（查数据库/检索知识库），
再把结果交回给大模型继续思考，最后输出答案。
就像"会自己查资料、自己存档的秘书"。

【这个文件里有什么？】
0. 意图路由 classify_intent()：先判断"这一轮用户到底想干什么"
   （寒暄闲聊 / 模糊需求 / 明确需求 / 无关需求），再决定这一轮是
   "只介绍能力""抛追问清单"还是"直接创作" —— 整条链路的总闸门
1. 工具1 story_material_search：RAG 检索工具 —— 让 Agent 会"查资料"
2. 工具2 story_db_tool：MySQL 持久化工具 —— 让 Agent 会"存档/翻旧账"
3. 系统提示词 SYSTEM_PROMPT：给 Agent 立的规矩（内容安全铁律 + 输出格式）
4. Agent 组装：create_tool_calling_agent + AgentExecutor
   （走原生 function-call；不用 create_react_agent，原因见第 5 步注释）
5. 多轮对话入口 chat()：先做意图路由，再把用户问题 + 历史记忆交给 Agent

【本课程最重要的一句话（必考）】
deepseek-chat 支持 function-call（工具调用），deepseek-reasoner 不支持，
所以模型必须用 deepseek-chat（config.py 里已做了启动拦截）。
"""
