# ⚠️ 这份清单必须和 SYSTEM_PROMPT 里【需求模糊时】那一节的清单保持一致，
#    因为第二轮要靠它出现在对话历史里，模型才能正确解读用户回的编号。
VAGUE_REPLY = """好呀！还差几件小事，我马上开写 👇
你可以直接回编号（例如「1A 2B 3B」），也可以自己一句话说，比如「小猫学分享，给 4 岁孩子看」

**1. 主角是谁？**
A 小动物　B 会说话的小物件　C 小朋友　D 我来定（写下来）

**2. 想讲什么道理？**
A 勇敢　B 分享　C 诚实　D 友爱或感恩　E 我来定（写下来）

**3. 给多大的孩子看？**
A 1-2 岁　B 3-6 岁　C 7-9 岁　D 10-12 岁

**4. 篇幅？**
A 短一点（约 200 字）　B 常规（300~500 字）　C 长一点（800 字以上）

回我一个编号或一句话，我就动笔 ✍️"""


def _already_asked(chat_history_text: str) -> bool:
    """功能：判断"最近一轮"系统是否刚问过那份选项清单（即正处在等用户回答的状态）
    入参：
        chat_history_text —— 拼好的历史对话文本
    返回：True —— 最近一轮就是追问清单；False —— 不是
    使用场景：模糊判定之前先看它。用户回答追问时可能只回"随便"两个字，
              那时也会被判成模糊需求，必须放行让模型去创作，绝不能反复追问。
    【为什么只看尾部 600 字】历史是"用户→智能体→用户→智能体"拼起来的，
              最后一段就是上一轮的系统回答。只查尾部可以避免"很久以前问过一次"
              就把后面所有输入都当成"已回答"，从而绕过追问。
    """
    tail = (chat_history_text or "")[-600:]
    return "主角是谁" in tail and "我来定" in tail


def _rule_intent(user_input: str, chat_history_text: str = "") -> str:
    """功能：规则法意图判定 —— 词表剥词 + 信号命中，**完全不调用模型**
    入参、返回值：同 classify_intent（返回四个类别字符串之一）
    使用场景：classify_intent() 的第一层。单独抽出来有两个目的：
        ① 让"规则本身判得对不对"能离线验证（tests/test_intent.py 跑的就是它）；
        ② 模型兜底万一不可用（断网/欠费），它就是可以安全退回的结果。

    【判定顺序有讲究（对齐业界意图路由的做法）】
      ⓪ 快捷判断：超过 40 字的输入默认当"明确需求"（长句一般自带信息量）；
         但句中出现"让权信号"（随便 / 你来定 / 帮我定）时先不放行 ——
         "我想要个故事，主题你随便定"这种啰嗦的模糊需求也很长。
      ① 先剥"寒暄词"        → 剥完为空 = 寒暄闲聊（"你好""谢谢""你能做什么"）
      ② 寒暄头 + 后半句无请求动词 → 也是寒暄（"谢谢，故事很好听"）
      ②-补 命中"让权信号"且句中没有具体要素 → 模糊需求（"你随意发挥""随便"）
      ③ 再剥"创作外壳词"    → 剥完为空 = 模糊需求（"写个故事""我要创作一些故事"）
      ④ 命中"创作信号词"（故事 / 主角 / 年龄 / 主题道理）= 明确需求，直接创作
      ⑤ 都不命中 = 其它需求，交给模型按【非故事类输入】处理
    为什么寒暄必须最先判："你好"剥掉创作外壳词后还剩一个"好"，
    若顺序反过来就会被误判成"其它"；而"讲个故事吧"不含寒暄词，自然落到第 ③ 步。

    【已知边界（讲清楚比藏起来好）】这是"词表剥词 + 信号命中"的规则法，
    不是让模型去判断。好处：不花钱、毫秒级、结果可复现、离线可测；
    代价：**没收录的说法会漏判**，而且漏了不报错，只是问卷悄悄不弹。
    【漏判怎么办】不是无限堆词表（追不上口语），而是两层应对：
      ① 每种踩过的说法都固化成用例（tests/test_intent.py），改词表时自动回归；
      ② 规则**没把握**的那两档交给模型复核 —— 见下面的 classify_intent()。
    """
    text = (user_input or "").strip()
    if not text:
        return "chitchat"
    # 长输入一般带着具体内容，直接按明确需求走（省去逐个词表匹配）。
    # ⚠️ 但"啰嗦的模糊需求"（"我想要个故事，主题主角你随便定"）也可能超过 40 字，
    #    无条件走快路径就会把它截胡、拿不到问卷。所以先看有没有让权信号：
    #    有 → 不做快路径判断，落回下面按词表老老实实剥一遍。
    if len(text) > 40 and not _LET_ME_DECIDE.search(text):
        return "create"

    # ---- ① 纯英文问候（hello / hi / thanks / bye）----
    # 中文词表管不到英文，单独判一次
    if re.fullmatch(r"[a-zA-Z\s,.!?~]+", text) and len(text) <= 20:
        if re.search(r"\b(hi|hello|hey|yo|thanks|thank you|thx|bye|goodbye)\b", text, re.I):
            return "chitchat"

    if re.search(r"[\u4e00-\u9fff]", text):
        # ---- ② 纯寒暄：剥掉寒暄/元问题词后什么都不剩 ----
        if _CHAT_WORDS.sub("", text).strip() == "":
            # 【例外】系统刚追问过一轮时，用户回"嗯嗯 / 好的 / 都行"这类应答词，
            # 实际意思是"你随便定吧"，应该直接去创作，而不是当成寒暄再客套一轮。
            # 真寒暄（"你好""谢谢"）不含这些应答词，仍按寒暄处理。
            if _already_asked(chat_history_text) and _AGREE_WORDS.search(text):
                return "create"
            return "chitchat"

        # ---- ②-b 寒暄/致谢开头 + 后半句没有创作请求 → 也是寒暄 ----
        # 现实输入常是"谢谢，故事很好听""你好呀～"这种"寒暄 + 情感表达"，
        # 剥词后剩一堆实词，但用户根本没在要故事 —— 不能因为句子里出现了
        # "故事"两个字就判成创作需求（否则会硬写一篇，很出戏）。
        head = _GREETING_HEADS.match(text)
        if head and not _REQUEST_VERBS.search(text[head.end():]):
            return "chitchat"

        # ---- ②-c 命中"让权信号" → 用户明说了"细节我不定、你来定" ----
        # 【为什么不靠剥词判它】像"我想要个故事但也不知道讲啥，你随便帮我定吧，
        #   反正是给小孩看的"这种啰嗦句，剥完永远会剩几个碎词（但是、反正、不知道…），
        #   词表追不上口语。既然用户已经把话说明白了，就直接认这个信号，不再猜。
        # 【为什么不直接 create】用户嘴上说"随便"，手上却给了主题的情况也有
        #   （"随便写个关于分享的故事"）—— 那是有要素的明确需求，不能弹问卷。
        #   所以配 _CONCRETE_ELEMENTS 一起看：有具体要素就让给正常流程去判。
        if _LET_ME_DECIDE.search(text) and not _CONCRETE_ELEMENTS.search(text):
            if _already_asked(chat_history_text) and not _REQUEST_VERBS.search(text):
                return "create"
            return "vague"

        # ---- ③ 模糊创作需求：剥掉意愿词、量词、语气词、故事名词后什么都不剩 ----
        if _SHELL_WORDS.sub("", text).strip() == "":
            # 【刚追问过一轮时怎么处理】
            #   ① 用户是在回答清单（"随便""都行""你决定"）→ 直接去创作，不再追问；
            #   ② 但他若又说了带请求动词的完整请求（"写个故事""帮我写个故事"）——
            #      说明这是他**又提了一轮新需求**，不是在回答，仍应弹问卷让他点选。
            # 【为什么必须区分】这里以前一律判 create：用户连着说两次"写个故事"，
            #   第二次起就再也不弹问卷了，用起来就像"点选功能坏了"。
            if _already_asked(chat_history_text) and not _REQUEST_VERBS.search(text):
                return "create"
            return "vague"

        # ---- ④ 有明确的故事要素 ----
        if _CREATE_SIGNALS.search(text):
            return "create"

    # 追问之后用户回得很短又没信息（"嗯嗯""好的"）→ 也直接去创作，不再追问
    if _already_asked(chat_history_text) and len(text) <= 12:
        return "create"

    # ---- ⑤ 其余：多为与儿童故事无关的需求，交给模型礼貌处理 ----
    return "other"


# ======================================================================
# 意图路由：置信度评估 + 模型兜底层
# ======================================================================
# 【为什么需要这一层】规则法在"词表里没有的说法"上会漏判。实测 26 条词表外
#   口语（"给我叨咕一个吧""来点哄睡的""想给孩子听点东西"）只判对 15 条 = 57.7%。
#   这类漏判**不报错**，只是问卷悄悄不弹，表现为"点选功能像是坏了"。
# 【思路】与其无限补词表，不如承认"规则不知道自己不知道"，让它**只做有把握的**，
#   没把握的交给模型复核。判据如下：
#     · 判成 chitchat / vague → 靠精确词表命中，实测很准 → 直接采信，不调模型
#     · 判成 create            → 命中"主题/主角/年龄/篇幅"等真要素才采信；
#                                只沾到"故事/童话/睡前"这类泛词 → 交模型复核
#     · 判成 other             → 本来就是"全都没命中"的不确定档 → 交模型复核
#   日常主流输入（"你好""写个关于分享的故事"）都落在第一、二种，零延迟零费用；
#   只有边缘说法才多花一次约 50 token 的调用。
_logger = logging.getLogger(__name__)


def _rule_is_confident(text: str, label: str, chat_history_text: str = "") -> bool:
    """功能：评估规则判定有没有把握（True = 有把握，不必调模型）
    入参：
        text              —— 用户本轮输入
        label             —— _rule_intent() 判出来的类别
        chat_history_text —— 历史对话文本（用于识别"追问后用户回了个应答词"）
    返回：True —— 直接采信规则结果；False —— 建议交模型复核
    使用场景：classify_intent() 用它决定"要不要花一次模型调用"
    """
    if label in ("chitchat", "vague"):
        # 这两档都是"剥完什么都不剩"判出来的，靠的是精确词表命中，实测很准。
        return True

    if label == "other":
        # "其它"是"所有词表都没命中"的兜底档 —— 规则自己也不知道该判什么。
        # 词表外的模糊需求大量落在这里（"想给孩子听点东西"），必须复核。
        return False

    # label == "create"：分两种情况
    #   ① 刚追问过一轮、用户只回了个应答词（"嗯嗯""都行"）→ 规则明确判它该去创作，
    #      这里若交给模型就坏了：模型只看"嗯嗯"两个字必然判成寒暄（chitchat），
    #      反而把规则原本正确的结果改错。
    #   ② 句子里出现了真要素（主题/主角/年龄/篇幅/续写改写指令）→ 采信。
    #   只沾到泛词（"睡前来一段"）→ 不采信，交模型。
    if _already_asked(chat_history_text) and (_AGREE_WORDS.search(text) or len(text) <= 12):
        return True
    return bool(_CONCRETE_ELEMENTS.search(text))


# 兜底专用的极简提示词：要求"只输出一个类别词"。
# 【为什么写得这么短】每轮对话都可能调它，token 全是钱和时间；
#   四类的定义各给一句最容易混的例子即可，不需要长篇说明。
_INTENT_FALLBACK_PROMPT = """用户在和一个"儿童故事创作"助手对话。判断下面这句话属于哪一类，只输出类别名（四个词之一），不要解释、不要标点。

chitchat —— 打招呼、道谢、告别、问助手是谁或能做什么
vague —— 想听儿童故事，但主题、主角、年龄都没说，细节要让助手自己定
create —— 已给出主题/主角/年龄/篇幅，或要求续写、改写、换结局
other —— 与儿童故事无关（写代码、查天气、翻译、聊别的等）

用户：{text}
类别："""

_intent_llm = None   # 模块级单例：判意图的小模型对象，复用以避免反复建连接

# ---- 熔断器：防止"网络不通时每次输入都干等一个超时" ----
# 【为什么需要】超时设成 6 秒，网络不通时每轮对话都要先白等 6 秒才降级 ——
#   答辩现场网一抖，体验就是"点一下发送，页面僵住六秒"，比判错还难受。
#   所以连续失败 2 次就暂时关掉兜底，冷却 60 秒后再自己试一次；
#   期间所有判定直接走规则法（虽然可能漏判，但**永远秒回**）。
_intent_fallback_fails = 0          # 连续失败次数
_INTENT_FALLBACK_TRIP = 2           # 连续失败几次后熔断
_INTENT_FALLBACK_COOLDOWN = 60.0    # 熔断后多少秒自动重试一次
_intent_fallback_open_until = 0.0   # 熔断到期的时间戳


def _get_intent_llm():
    """功能：创建"意图兜底"专用的极轻量模型对象（懒加载单例）
    入参：无（模型名/密钥来自 config）
    返回：ChatDeepSeek 对象
    使用场景：_llm_intent() 内部调用
    【为什么不复用 create_llm()】那个是给"创作"用的：temperature=0.9、
      max_tokens=4000、超时 60 秒。判意图要的正好相反 —— 确定性（温度 0）、
      极省输出（几个 token）、快速失败（超时短）。参数冲突，必须单独建。
    """
    global _intent_llm
    if _intent_llm is None:
        _intent_llm = ChatDeepSeek(
            model=config.DEEPSEEK_MODEL,             # 必须 deepseek-chat（reasoner 不支持 function-call）
            api_key=config.DEEPSEEK_API_KEY,
            api_base=config.DEEPSEEK_BASE_URL,
            temperature=0,                           # 分类任务要确定性，不许发挥
            max_tokens=8,                            # 只需要一个词
            timeout=config.INTENT_FALLBACK_TIMEOUT,  # 短超时：宁可退回规则结果，也不卡住对话
            max_retries=0,                           # 失败就降级，不重试拖时间
        )
    return _intent_llm


def _llm_intent(text: str, rule_label: str) -> str:
    """功能：调一次极轻量的大模型做意图分类（规则没把握时的兜底层）
    入参：
        text       —— 用户本轮输入
        rule_label —— 规则法的判定（任何异常时原样退回它）
    返回：四个类别字符串之一
    使用场景：classify_intent() 内部调用
    【最重要的一条：本函数永远不抛异常、永远有返回值】
      意图判定在整条链路最前面，它挂了整轮对话就挂了。所以超时、欠费、
      密钥失效、返回格式跑偏…… 一律吞掉并退回 rule_label。
      宁可"退化成原来的规则法"，也绝不能让用户点一下发送就报错。
    【第二条：失败会累积成熔断】连错 2 次就暂时不再尝试（见上面的熔断器变量），
      避免"网络不通 → 每轮都白等 6 秒"。熔断 60 秒后自动放行重试一次。
    """
    global _intent_fallback_fails, _intent_fallback_open_until

    if (_intent_fallback_fails >= _INTENT_FALLBACK_TRIP
            and time.time() < _intent_fallback_open_until):
        return rule_label        # 熔断中：直接走规则，一秒都不多等

    try:
        response = _get_intent_llm().invoke(_INTENT_FALLBACK_PROMPT.format(text=text))
        raw = (getattr(response, "content", "") or "").strip().lower()
        # 模型偶尔会带标点或前后缀（"类别：vague。"），所以按包含关系解析，
        # 只取第一个出现的类别名，不要求整串严格相等。
        found = re.findall(r"chitchat|vague|create|other", raw)
        _intent_fallback_fails = 0        # 成功即清零，恢复健康状态
        return found[0] if found else rule_label
    except Exception as error:
        _intent_fallback_fails += 1
        _intent_fallback_open_until = time.time() + _INTENT_FALLBACK_COOLDOWN
        _logger.warning(
            "意图兜底不可用（连续第 %d 次失败，本次已退回规则判定；"
            "再失败 %d 次将熔断 %d 秒）：%s",
            _intent_fallback_fails,
            max(0, _INTENT_FALLBACK_TRIP - _intent_fallback_fails),
            int(_INTENT_FALLBACK_COOLDOWN), error)
        return rule_label


def classify_intent(user_input: str, chat_history_text: str = "",
                    use_fallback=None) -> str:
    """功能：判断用户这句话属于哪一类意图（本项目的"意图路由"总入口）
    入参：
        user_input        —— 用户本轮输入
        chat_history_text —— 历史对话文本（用于判断"是否刚追问过"）
        use_fallback      —— 是否允许模型兜底。None（默认）跟 config.INTENT_FALLBACK 走；
                             True/False 用于临时指定（测试里做对照实验用）
    返回：四个字符串之一
        "chitchat" —— 寒暄闲聊：打招呼 / 道谢 / 告别 / 问"你是谁、能做什么"
        "vague"    —— 模糊创作需求：只表达了"想听故事"，主题/主角/年龄全都没给
        "create"   —— 明确创作需求：给了主题、主角、年龄、篇幅中任意一项，或要求续写改写
        "other"    —— 其它（多为与儿童故事无关的需求，如写代码、查天气）
    使用场景：chat() / chat_stream() 在调用大模型之前先判一次，按类别分别处理；
              只有判成 "vague" 才会弹需求澄清问卷

    【两层结构】
      第一层 _rule_intent()      —— 词表剥词 + 信号命中，零成本、毫秒级
      第二层 _rule_is_confident() —— 有把握就用第一层结果；没把握调模型复核
    配置开关在 .env：INTENT_FALLBACK=false 可整体关掉第二层（断网演示时的保险）。
    """
    label = _rule_intent(user_input, chat_history_text)

    if _rule_is_confident(user_input, label, chat_history_text):
        return label

    if use_fallback is None:
        use_fallback = config.INTENT_FALLBACK
    if not use_fallback:
        return label

    final = _llm_intent(user_input, label)
    # 记一条日志：答辩时想说明"兜底到底改了什么"可以直接看这里
    if final != label:
        _logger.info("意图兜底修正：规则=%s → 模型=%s ｜ 输入=%r", label, final, user_input)
    else:
        _logger.info("意图兜底确认：%s ｜ 输入=%r", label, user_input)
    return final


def is_vague_request(user_input: str) -> bool:
    """（兼容接口）判断输入是不是"只说了想听故事、没给任何具体内容"的模糊需求
    入参：
        user_input —— 用户本轮输入
    返回：True —— 模糊需求（应先追问）；False —— 其它
    使用场景：保留给外部按旧接口调用；主流程现在统一走 classify_intent()
    """
    return classify_intent(user_input) == "vague"


# ======================================================================
# 第 9 步：对话入口（网页每轮对话调用它）
# ======================================================================
def chat(user_input: str, chat_history_text: str = "", session_id: str = "") -> dict:
    """功能：执行一轮对话（把用户问题 + 历史记忆交给 Agent）
    入参：
        user_input        —— 用户当前输入的问题
        chat_history_text —— 历史对话文本（由 app.py 从 MySQL 读取并格式化）
        session_id        —— 本轮所属会话ID。传了就绑定到请求级上下文，
                             工具2保存故事时据此写入正确的 session_id。
                             （不传也能用：调用前先 set_current_session() 即可）
    返回：字典 result：
          result["output"]              —— Agent 的最终回答（故事正文 / 能力介绍）
          result["intermediate_steps"]  —— 工具调用过程列表（网页日志展示用）
          result["style_hint"]          —— 本轮注入的补充指令（创作变奏 / 非创作提示）
          result["intent"]              —— 本轮意图类别（chitchat/vague/create/other）
          result["clarify"]             —— 本轮是否需要弹"需求澄清问卷"（True/False）
          result["saved_story"]         —— 本轮真正存进库的那篇故事（没存则为 None）
    使用场景：app.py 在用户发消息后调用
    """
    # ---- 第零步：绑定本轮上下文 ----
    # 【为什么必须放最前面】
    #   ① 把会话ID写进本执行上下文的私有副本，工具2 存故事时读得到；
    #   ② 把"最近保存的故事"清零。必须每轮清 —— 否则线程被 Streamlit 复用时
    #      可能读到上一轮的残留，出现"这一轮明明没存故事，页面却补了上一篇正文"的怪现象。
    reset_turn_context(session_id)

    # ---- 第一步：意图路由（代码兜底，不依赖模型自觉）----
    # 把用户这句话归到四类之一，再决定"这一轮到底做什么"：
    #   chitchat 寒暄闲聊 → 只介绍能力，不抛清单、不调工具、不创作
    #   vague    模糊需求 → 直接返回选项清单（连大模型都不调用）
    #   create   明确需求 → 注入"创作变奏"，正常检索 + 创作 + 存档
    #   other    其它需求 → 按【非故事类输入】礼貌处理
    # 【为什么关键行为要用代码判】提示词约束是概率性的：实测"我要创作故事"写在
    # 提示词里也常被模型当成明确指令直接开写。代码判定才是确定性的。
    intent = classify_intent(user_input, chat_history_text)

    # 档位 1：模糊需求 → 不调用大模型，直接让网页弹"需求澄清问卷"
    # 【clarify 这个标记的作用】app.py 看到它就把这条回复渲染成
    #   可点选的问卷（单选卡片 + 其他自定义 + 翻页），而不是一段让用户
    #   自己敲编号的文字清单 —— 交互更顺，也彻底避免了手敲格式错误。
    #   output 里保留那份文字清单，作用是：
    #     ① 切换历史会话时，这条记录还能正常显示；
    #     ② 它会被存进对话历史，_already_asked() 靠它判断"刚问过一轮"。
    if intent == "vague":
        return {
            "output": VAGUE_REPLY,
            "intermediate_steps": [],   # 没调用任何工具（网页端据此不显示变奏面板与日志）
            "style_hint": "",
            "intent": intent,
            "clarify": True,
            "saved_story": None,        # 澄清轮只问不写，不存故事
        }

    try:
        # 【本轮注入什么，由意图决定】
        #   create         → 注入"创作变奏"（随机设定 + 必须输出完整正文的强提醒）
        #   chitchat/other → 注入"非创作提示"（明确告知不是创作请求，别硬编故事）
        # 【为什么必须分开】变奏里那句"本轮必须写出完整故事正文"是对创作轮的硬要求；
        #   如果对"你好""帮我写代码"也无条件注入，等于在逼模型硬编一个故事 ——
        #   这正是"打招呼也可能冒出故事"的根因。
        if intent in ("chitchat", "other"):
            style_hint = _NON_CREATE_HINT
        else:
            style_hint = build_style_hint()

        # 调用 Agent。注意 chat_history / style_hint 这两个键名必须和提示词模板里的
        # {chat_history} / {style_hint} 占位符一致，LangChain 会自动替换。
        result = get_agent_executor().invoke(
            {
                "input": user_input,                 # 对应模板里的 {input}
                "chat_history": chat_history_text,   # 对应模板里的 {chat_history}
                "style_hint": style_hint,            # 对应模板里的 {style_hint}
            }
        )
        # 把本轮注入内容与意图一并带回：
        #   style_hint —— 网页端展示"这次为什么不一样"（答辩演示用）
        #   intent     —— 便于排查与统计（网页端暂不展示）
        #   clarify    —— 本轮不是澄清轮（只有模糊需求才需要弹问卷）
        result["style_hint"] = style_hint
        result["intent"] = intent
        result["clarify"] = False
        # 本轮真正存进库的那篇故事（没存就是 None）——
        # 直接从工具调用参数里还原，不依赖任何跨调用共享状态
        result["saved_story"] = _find_saved_story(result.get("intermediate_steps", []))
        return result
    except Exception as error:
        # 统一转成中文友好错误（API超时、网络异常、工具异常都会走到这里）
        # from error：保留异常链，方便排查底层原因
        raise RuntimeError(
            f"智能体调用失败：{error}\n"
            f"请检查：① DeepSeek API 密钥是否正确；"
            f"② 网络是否可达 api.deepseek.com；③ .env 配置是否正确"
        ) from error


# ======================================================================
# 第 10 步：流式版对话入口（网页端的"打字机效果"）
# ======================================================================
# 【为什么要流式】同步 invoke() 必须等模型把整篇故事写完才一次性返回，
# 每轮干等约 20 秒，页面上只有一个转圈 —— 台下看着像程序卡死。
# 流式输出让正文逐字出现，并把"正在检索素材""正在保存"等阶段实时显示出来。
#
# 【最大的坑：模型的"中间思考"会混在 token 流里】
# 实测发现，模型在每轮工具调用之前会先吐一段**英文内心独白**，例如：
#     "I'll help you create a story... Let me first search for relevant materials."
# 要是照单全收地流到页面上，家长/老师会先读到一大段英文，体验直接崩掉。
#
# 【怎么过滤】利用本 Agent 固定的执行流程：
#     检索素材 → 生成正文（作为存档工具的入参）→ 存档成功 → 复述正文
# 于是规则定为：
#   ① 存档工具（story_db_tool）**成功返回之前**，所有文本一律只缓冲、不展示
#      —— 那必然是模型的思考；
#   ② 存档成功之后的文本才是要给孩子看的正文，实时逐字流出；
#   ③ 万一模型没走存档这条路（寒暄闲聊轮），或中途存档失败，
#      就在收尾时用 AgentExecutor 认定的最终答案兜底输出。
# 这样既保住了流式手感，又保证"屏幕上出现的每一句都是给人看的"。

# 阶段提示文案：工具名 → (刚开始时的提示, 结束时的提示)
_TOOL_STAGE_TEXT = {
    "story_material_search": ("🔍 正在检索故事素材…", "✅ 素材检索完成，马上开始创作"),
    "story_db_tool": ("💾 正在把故事保存到数据库…", "✅ 故事已存档，正在输出正文"),
}


def _stage_text(tool_name: str, phase: str) -> str:
    """功能：把工具名翻译成给用户看的阶段提示
    入参：tool_name —— 工具名；phase —— "start" 或 "end"
    返回：一行中文提示
    """
    pair = _TOOL_STAGE_TEXT.get(
        tool_name, ("🔧 正在调用工具 %s…" % tool_name, "✅ %s 执行完成" % tool_name))
    return pair[0] if phase == "start" else pair[1]


def _build_steps(step_map: dict, order: list) -> list:
    """功能：把流式收集到的工具调用还原成 intermediate_steps 格式
    入参：step_map —— {run_id: {tool, input, output}}；order —— run_id 的先后顺序
    返回：[(AgentAction, observation), ...]，形状与 executor.invoke() 一致，
          这样网页的"工具调用日志"面板不改代码就能继续展示。
    """
    from langchain_core.agents import AgentAction
    steps = []
    for run_id in order:
        info = step_map.get(run_id)
        if not info:
            continue
        action = AgentAction(tool=info["tool"], tool_input=info["input"], log="")
        steps.append((action, info["output"]))
    return steps


async def chat_stream(user_input: str, chat_history_text: str = "", session_id: str = ""):
    """功能：异步流式版对话入口（网页端用它实现"打字机效果"+ 实时阶段提示）
    入参：同 chat()
    产出（异步生成器，逐个 yield 事件字典）：
        {"type": "stage", "text": "🔍 正在检索故事素材…"}   阶段提示
        {"type": "delta", "text": "小兔子……"}              正文增量（逐字）
        {"type": "done",  "result": {...}}                  结束，result 同 chat() 的返回
    使用场景：app.py 用 asyncio 边收边刷页面
    """
    reset_turn_context(session_id)

    # 【为什么放线程里跑】意图判定在规则没把握时会调一次大模型（约 1 秒）。
    # 在 async 函数里**同步**调用会阻塞整个事件循环 —— 表现是"流式输出卡住、
    # 页面半天不刷新"。丢到线程里执行，事件循环就能继续把阶段提示推给前端。
    intent = await asyncio.to_thread(classify_intent, user_input, chat_history_text)

    # 档位 1：模糊需求 → 不调模型，直接给澄清标记（同 chat()）
    if intent == "vague":
        yield {"type": "done", "result": {
            "output": VAGUE_REPLY,
            "intermediate_steps": [],
            "style_hint": "",
            "intent": intent,
            "clarify": True,
            "saved_story": None,
        }}
        return

    if intent in ("chitchat", "other"):
        style_hint = _NON_CREATE_HINT
        # 非创作轮基本不会调工具，不存在"思考文本混进来"的问题 → 直接流，手感更好
        direct_stream = True
    else:
        style_hint = build_style_hint()
        direct_stream = False      # 创作轮：等存档成功后再开始流正文

    inputs = {
        "input": user_input,
        "chat_history": chat_history_text,
        "style_hint": style_hint,
    }

    executor = get_agent_executor()

    step_map = {}          # run_id -> {tool, input, output}
    step_order = []        # 保持工具调用的先后顺序
    running_tools = 0      # 正在执行的工具数（Agent 可能并行调多个）
    story_saved = False    # 存档工具是否已成功返回（= 可以开始流正文了）
    streamed = []          # 已经流出去的正文片段
    buffered = []          # 存档之前缓冲下来的文本（多半是模型的思考，最终丢弃）
    final_output = ""      # AgentExecutor 认定的最终答案（兜底用）

    async for event in executor.astream_events(inputs, version="v2"):
        etype = event["event"]

        # ---- 工具开始 ----
        if etype == "on_tool_start":
            running_tools += 1
            rid = event["run_id"]
            step_map[rid] = {
                "tool": event.get("name", ""),
                "input": event["data"].get("input"),
                "output": None,
            }
            step_order.append(rid)
            yield {"type": "stage", "text": _stage_text(event.get("name", ""), "start")}

        # ---- 工具结束 ----
        elif etype == "on_tool_end":
            running_tools = max(0, running_tools - 1)
            rid = event["run_id"]
            output = event["data"].get("output")
            if rid in step_map:
                step_map[rid]["output"] = output
            tool_name = event.get("name", "")
            yield {"type": "stage", "text": _stage_text(tool_name, "end")}
            # 存档成功 = 正文马上开始（见本段开头的流程说明）
            if tool_name == "story_db_tool" and "已成功保存" in str(output):
                story_saved = True

        # ---- 模型吐字 ----
        elif etype == "on_chat_model_stream":
            chunk = event["data"].get("chunk")
            piece = getattr(chunk, "content", "") or ""
            if not piece:
                continue        # 这一段是工具调用的结构化参数，不是给人看的文字
            if direct_stream or story_saved:
                streamed.append(piece)
                yield {"type": "delta", "text": piece}
            else:
                buffered.append(piece)

        # ---- 整个 Agent 跑完：拿到最终答案 ----
        elif etype == "on_chain_end" and event.get("name") == "AgentExecutor":
            out = event["data"].get("output")
            if isinstance(out, dict):
                final_output = out.get("output", "") or ""

    # ---- 收尾兜底 ----
    # 走到这里如果流式阶段一句正文都没吐出来（没走存档 / 存档失败 / 模型没复述），
    # 就用最终答案补一次，保证页面上一定有内容。
    if not streamed:
        fallback = final_output or "".join(buffered)
        if fallback:
            streamed.append(fallback)
            yield {"type": "delta", "text": fallback}

    # 用和同步入口完全相同的方式还原"本轮存的那篇故事"：
    # 工具的调用参数里本来就有完整正文，重算一遍即可，不依赖任何跨上下文的状态。
    steps = _build_steps(step_map, step_order)

    yield {"type": "done", "result": {
        "output": "".join(streamed) or final_output,
        "intermediate_steps": steps,
        "style_hint": style_hint,
        "intent": intent,
        "clarify": False,
        "saved_story": _find_saved_story(steps),
    }}


