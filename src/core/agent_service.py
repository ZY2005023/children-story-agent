def get_recent_used_elements(limit: int = 6) -> list:
    """功能：从数据库读出最近几篇已保存故事的「主角 / 标题」，作为本次要避开的清单
    入参：
        limit —— 最多取几篇（默认 6 篇）
    返回：字符串列表，例如 ["小兔子跳跳", "《彩虹色的分享》"]；数据库异常时返回 []
    使用场景：build_style_hint() 调用 —— 防止模型换汤不换药，
              把刚写过的主角原样再用一遍（同一个会话里连着写两篇尤其明显）
    """
    try:
        stories = DBUtil.get_all_stories()      # 已按 id 倒序，第一条就是最新那篇
    except Exception:
        # 数据库不可用不应该影响创作，静默降级为空清单
        return []
    used = []
    for story in stories[:limit]:
        role = str(story.get("main_role") or "").strip()
        title = str(story.get("story_title") or "").strip()
        # 「未指定」这类占位内容没有参考价值，不要塞进避开清单
        if role and role not in ("未指定", "无"):
            used.append(role)
        if title and title not in ("未指定", "无") and len(title) <= 20:
            used.append(f"《{title}》")
    # 去重但保持顺序（dict.fromkeys 是 Python 3.7+ 会保留插入顺序的去重写法）
    return list(dict.fromkeys(used))


def build_style_hint() -> str:
    """功能：随机生成一段「本轮创作变奏」，注入提示词用来避免故事千篇一律
    入参：无
    返回：可直接拼进提示词的文本（每轮都不一样）
    使用场景：chat() 每轮调用一次
    """
    picks = []      # 抽中的维度，元素是 (维度名, 具体取值)
    for name, options in _STYLE_POOL.items():
        picks.append((name, random.choice(options)))

    # 【为什么要压缩】变奏内容紧贴用户输入，如果写得太长（原来有 ①②③ 三条说明），
    # 会稀释模型对"必须输出故事正文"这条硬要求的注意力 —— 实测出现过
    # "第二轮只回了 8 个字（已存入故事库）"的偷懒情况，所以正文提醒直接压在最后。
    lines = [
        "★ 本节只对「全新创作」生效：续写 / 扩写 / 改结局时沿用上一轮的角色和场景；"
        "用户明确指定的要求（点名的主角、年龄、主题）永远优先于下面的设定。",
        "",
    ]
    for name, value in picks:
        lines.append(f"- {name}：{value}")

    used = get_recent_used_elements()
    if used:
        lines.append("")
        lines.append(
            "- 【必须避开】下面这些主角 / 标题最近刚刚写过，本次不要再用："
            + "、".join(used)
        )

    lines.append("")
    lines.append(
        "⚠️ 最后提醒：本轮最终回答必须原样写出**完整的故事正文**（角色介绍 + 故事情节 + 教育小道理）。"
        "存档是后台动作、用户看不到，只回一句「已存入故事库」等于什么也没交付。"
    )
    return "\n".join(lines)


# ======================================================================
# 第 3 步：定义工具1 —— 儿童故事知识库 RAG 检索工具
# ======================================================================
@tool
def story_material_search(query: str) -> str:
    """在儿童故事素材知识库中检索与 query 相关的经典故事素材（RAG检索工具）。
    适用场景：创作故事前检索参考素材，借鉴经典故事的风格、桥段、角色设定。
    参数：query —— 检索问题或关键词，例如"关于分享的小故事素材"。
    返回：检索到的相关故事片段文本；知识库为空或没有匹配时返回提示文字。
    """
    # 【调用时机】当需要参考已有故事素材的风格/桥段时调用
    # 【原理】把 query 交给 RAG 服务：向量化 → FAISS 相似度检索 → 格式化文本
    #
    # 【@tool 怎么理解】@tool 是 LangChain 提供的装饰器，作用是把一个普通 Python
    # 函数"升级"为智能体可调用的工具。升级的关键是函数的 docstring ——
    # 它就是交给大模型的"工具说明书"：模型只看得见 docstring 里写的用途、
    # 参数说明、返回说明，据此决定何时调用、参数怎么填。
    # 所以：docstring 写得越清楚，模型用得越准。
    try:
        return rag_service.retrieve(query)
    except Exception as error:
        # 工具内部捕获异常，返回错误文字而不是抛出，
        # 这样 Agent 拿到错误说明后还能继续对话，不会整个程序崩溃
        return f"知识库检索失败：{error}"


# ======================================================================
# 第 4 步：定义工具2 —— 故事持久化 MySQL 工具（保存 + 查询二合一）
# ======================================================================
@tool
def story_db_tool(
    action: str,
    story_title: str = "",
    main_role: str = "",
    age_group: str = "",
    story_content: str = "",
    moral: str = "",
    keyword: str = "",
) -> str:
    """儿童故事数据库工具：把生成完成的儿童故事保存进 MySQL，或查询历史已生成的故事。
    参数说明：
    - action：操作类型，只能是 "save"（保存故事）或 "query"（查询历史故事）；
    - story_title：故事标题（action="save" 时必填）；
    - main_role：主角名字（action="save" 时必填）；
    - age_group：适合年龄段，如"3-6岁"（action="save" 时必填）；
    - story_content：故事完整正文（action="save" 时必填）；
    - moral：教育寓意（action="save" 时必填）；
    - keyword：按标题模糊查询的关键词（action="query" 时选填，为空则查询全部故事）。
    返回：操作结果说明文本。
    """
    # 【调用时机】① 故事创作完成后保存入库 ② 用户想查看历史已生成的故事
    # 【原理】直接调用 db_util.py 里的数据库方法，Agent 不用自己写 SQL
    #
    # 【设计说明】一个工具干两件事（save / query），用 action 参数区分——
    # 这本身就是函数式设计的经典模式，对应 Day1 练习 8 的 if/elif/else 骨架。
    # 带默认值的参数（story_title: str = ""）让"查询"时可以不传保存类参数。
    # 【会话归属从哪来】从请求级上下文读，而不是模块级全局变量 —— 见第 1 步注释。
    try:
        # ---- 情况 1：保存故事 ----
        if action == "save":
            # 保存前先做"参数体检"：标题和正文是必填的
            if not story_title.strip() or not story_content.strip():
                return "保存失败：故事标题和正文不能为空"
            # 【防脏数据】模型有时会把标题写成"《小汤勺的秘密留言》"（自带书名号），
            # 而网页展示时会再包一层《》，结果变成"《《…》》"。这里统一剥掉首尾书名号。
            clean_title = story_title.strip().strip("《》").strip() or story_title.strip()
            DBUtil.save_story(
                session_id=get_current_session() or "default_session",  # 归属当前会话
                story_title=clean_title,                # strip 去掉首尾空格（防脏数据）
                main_role=main_role.strip() or "未指定", # or 兜底：模型漏传参数也不崩
                age_group=age_group.strip() or "未指定",
                story_content=story_content,
                moral=moral.strip() or "未指定",
            )
            # 存档成功。这里**不再**另外记一份"最近保存的故事"——
            # 网页需要兜底展示时，会从本次工具调用的参数里直接还原（见 _story_from_tool_args）。
            return f"✅ 故事《{clean_title}》已成功保存到数据库"

        # ---- 情况 2：查询历史故事 ----
        elif action == "query":
            stories = DBUtil.get_all_stories(keyword=keyword)
            if not stories:
                return "（数据库中暂无历史故事记录）"
            # 把查询结果拼成一行行清单，方便大模型阅读后转述给用户
            lines = []
            for i, s in enumerate(stories, 1):
                lines.append(
                    f"{i}. 《{s['story_title']}》｜主角：{s['main_role']}"
                    f"｜适合：{s['age_group']}｜保存时间：{s['create_time']}"
                )
            return "历史故事列表：\n" + "\n".join(lines)

        # ---- 情况 3：action 写错了 ----
        else:
            return f"操作类型错误：{action}，action 只能是 'save' 或 'query'"
    except Exception as error:
        # 数据库异常也返回文字而不是崩溃，Agent 会转告用户"保存失败"
        return f"数据库操作失败：{error}"


