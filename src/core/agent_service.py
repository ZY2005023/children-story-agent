# 第 5 步：提示词模板（注意：这里不用写 ReAct 的文本格式了）
# ======================================================================
# 【为什么模板里没有 Thought/Action/Observation 格式说明了？】
# 因为 create_tool_calling_agent 走的是「原生 function-call」：
#   工具的"函数签名 + docstring"会被自动转成 JSON Schema 交给 DeepSeek，
#   模型需要调工具时直接输出结构化调用，不需要我们再教它写 "Action: xxx" 文本。
#   所以模板只需要提供 系统提示词 + 对话历史 + 用户输入 + 草稿区 四块。
#
# 【对比·为什么不用 create_react_agent（重要，答辩可能被问）】
#   langchain 0.3 的 create_react_agent 是「文本式 ReAct」：
#   它靠 ReActSingleInputOutputParser 解析模型输出的文本
#   （必须出现 "Action:" / "Action Input:" / "Final Answer:"），
#   而且动作输入只能是一段字符串，无法展开成多个关键字参数——
#   我们 story_db_tool 有 7 个参数，用文本式 ReAct 会把整串 JSON
#   当成第一个参数 action 传进去，直接报"操作类型错误"。
#   所以多参数工具必须用 create_tool_calling_agent。
#
# 【ReAct 思想依然成立】Thought（思考）→ Action（行动）→ Observation（观察）
#   这个循环仍然在跑，只是"行动"从写文本变成了原生 function-call。
#   网页端的"工具调用日志"面板依然能看到每一步的输入与返回。
# 【为什么把变奏放在"用户输入之后"而不是之前】提示词里越靠近生成位置的内容，
# 模型越容易遵守。实测：变奏放在 input 之前时，会稀释"必须输出故事正文"这条硬要求，
# 出现过"第二轮只回一句（已存入故事库）"的情况；挪到 input 之后、并让变奏末尾
# 直接压一句正文提醒，就稳住了。
