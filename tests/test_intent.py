r"""
======================================================================
test_intent.py —— 意图路由验收测试（第 5 层：意图判定）
======================================================================
运行方式（推荐在项目根目录执行）：
    .venv\Scripts\python.exe -m tests.test_intent
（也可以直接 .venv\Scripts\python.exe tests\test_intent.py，脚本会自动把项目根加入搜索路径）

【这一层为什么单独测】
classify_intent() 是"要不要弹需求澄清问卷"的唯一判据，纯代码、**无副作用**
（不调 API、不查库、不写库），所以可以放心地跑大量用例。

【判错的后果是"静默失效"】
判错时页面上看不到任何报错 —— 该弹问卷却直接开写、该寒暄却硬编故事。
2026-09-23 就踩过一次：剥词表漏了量词"一"和全角标点"」"，
"我要创作一些故事""写个故事」" 被判成"明确需求"，问卷根本不弹，日志却干干净净。
同一天又发现同一病的两个新变种：口语词漏收（"整点故事""搞个故事""安排一个童话"
"你随意发挥"），以及"长句 = 明确需求"的快路径会截胡啰嗦的模糊需求
（"我想要个故事，主题你随便定"共 41 字 → 直接开写，问卷不弹）。
所以这一层必须有用例兜着：**每发现一个漏判说法，就往用例表里加一条**。

【五条验收线】
    ① 模糊说法 → vague（弹问卷）    含口语、量词、全角标点等各种写法
    ② 明确需求 → create（直接创作） 不能因为补了壳词，把真需求也一起剥掉
    ③ 寒暄     → chitchat          打招呼不能被误判成"要故事"
    ④ 追问后再输入 → 请求类仍弹问卷、应答类直接创作
    ⑤ 词表外说法 → 模型兜底能救回来（需联网，离线自动跳过）

【①②③④ 跑的是"规则层"（use_fallback=False）】
纯代码、零网络、零成本。改完词表必须全绿 —— 这是离线也能跑的底线。

【⑤ 跑的是"完整链路"（use_fallback=True，也就是用户实际走的那条路）】
规则法靠词表匹配，词表外的说法一定会漏（实测 54 条词表外说法漏 19 条 = 35%）。
这一层验证的不是"规则不漏"，而是"漏了之后模型兜底能救回来"，
以及**绝不能把明确需求判成模糊**（那会让用户点了发送却被反问，比漏弹问卷更伤）。
"""
import sys
from pathlib import Path

# 把"项目根目录"加入模块搜索路径，保证无论怎么运行这个脚本都能导入 src 包
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src import config
from src.core.agent_service import classify_intent, VAGUE_REPLY

# ======================================================================
# 用例表
# ======================================================================
# ① 模糊需求：只表达了"想听故事"，主题/主角/年龄全没给 → 应该弹问卷
VAGUE_CASES = [
    # 最普通的几种说法
    "写个故事", "写个故事吧", "讲个故事", "来个故事", "创作一个故事",
    "我要创作故事", "帮我写一个故事", "我想听故事", "给我讲个故事",
    "帮我创作一篇故事", "写一篇故事", "来点故事",
    # 随便 / 让你定
    "随便来一个", "随便", "都行", "你看着办",
    # 带标点（全角标点必须能剥干净）
    "写个故事。", "写个故事！", "写个故事」", "「写个故事」",
    # 带量词（"一""几""两"这些单字要能剥掉，只收"些""个"是不够的）
    "我要创作一些故事", "我想创作一些故事", "写一些故事",
    "给我来几个故事", "写几篇故事", "我要听一些故事",
    # 带同义动词 / 副词
    "我想看故事", "再来一个故事",
    # 口语说法（2026-09-23 补测：曾漏判成 create）
    # 漏因是壳词表缺"整点/搞/安排/随意/发挥/没想好/有没有"这些口语词
    "来段小故事", "给我整个故事听听", "想听个故事", "讲个故事呗",
    "有没有故事", "故事", "讲一个嘛", "给我来段睡前故事",
    "你随意发挥", "我没想好 你看着办", "整点故事", "安排一个童话",
    "搞个故事",
    # 啰嗦的长句模糊需求：超过 40 字也不能走"长句 = 明确需求"的快路径，
    # 必须靠"让权信号（随便/帮我定）"识别出来 —— 见 _LET_ME_DECIDE
    "我想要一个故事但是我自己也不知道该讲什么主题你随便帮我定一个就行反正是给小孩子看的",
]

# ② 明确需求：给了主角 / 主题 / 年龄段 / 篇幅中任意一项 → 直接创作，不追问
CREATE_CASES = [
    "写个小乌龟学分享的故事，给 4 岁孩子看",
    "创作一个关于勇敢的小兔子的故事，适合3-6岁，教育孩子不要害怕黑暗",
    "生成野驴勇敢冲的故事，关于勇敢的故事",
    "我要一个关于诚实的故事，给 7 岁孩子",
    # 反例：嘴上说"随便"，但已经给了主题/主角 → 仍算明确需求，不能弹问卷。
    # 这组用来防止"让权信号"判得太狠，把真需求也拦下来。
    "随便写个关于分享的故事",
    "你们随便，主角是小猫，5 岁",
    "你看着办，讲勇敢的故事",
]

# ③ 寒暄闲聊 → 介绍能力，不弹问卷、不创作
CHITCHAT_CASES = [
    "你好", "你好呀", "谢谢", "再见", "hello", "你能做什么",
]

# ④ 刚弹过一轮问卷后再输入（历史尾部含清单）：
#    带请求动词的完整请求 = 用户又提了一轮新需求 → 仍然弹问卷
AFTER_ASK_REQUEST = ["写个故事", "我要创作一些故事", "帮我写个故事", "再来一个故事"]
#    不带请求动词的短应答 = 用户在回答清单 → 直接创作，不再追问
AFTER_ASK_ANSWER = ["随便", "都行", "你看着办", "小动物"]

# 模拟"上一轮系统的回复就是那份追问清单"的对话历史
ASKED_HISTORY = "用户：写个故事\n助手：" + VAGUE_REPLY + "\n"

# ⑤ 词表外新说法：规则法判不准，靠模型兜底救回来（需联网）
#    【怎么选出来的】刻意只用"词表里没有的动词/名词"，以及**不含"故事"二字**
#    的说法（"想给孩子听点东西""现在几点了"）。这些是 2026-09-24 实测中
#    规则法真实漏判过的说法，漏判率 35%，所以必须固化成用例。
FALLBACK_VAGUE = [
    "给我叨咕一个吧", "睡前来一段", "随便挑个题材写写", "帮我凑一个",
    "想给孩子听点东西", "来点哄睡的", "闲得慌，讲点啥吧", "有没有那种小故事",
    "给我念一段吧", "你出个主意", "来个新鲜的", "给孩子讲个",
]
FALLBACK_CREATE = [
    "要一个讲勇气的，主角是蒲公英", "孩子六岁了，想听关于友谊的",
    "帮我写个关于星星的，睡前给娃念", "要一个能让孩子学会等待的故事",
    "写一个教孩子守时的", "要个短一点的，关于诚实的", "写个三分钟的，主题是别乱跑",
]
FALLBACK_CHITCHAT = [
    "你是机器人不", "你就是那个写故事的吧", "这故事真好听",
    "你能写什么来着", "你是AI吧",
]
FALLBACK_OTHER = [
    "帮我翻译一段英文", "双十一买啥划算", "帮我把这段话润色一下",
    "怎么用 excel 做透视表", "现在几点了", "明天天气如何",
]


# ======================================================================
# 执行与统计
# ======================================================================
_passed = 0
_failed = []


def check(case, expect, history="", use_fallback=False):
    """跑一条用例：返回 (是否通过, 实际判定)
    use_fallback 默认 False —— 用例默认只测**规则层**，保证离线、秒级、零成本；
                 只有第 ⑤ 组（词表外说法）才显式传 True 去测模型兜底。
    """
    global _passed
    got = classify_intent(case, history, use_fallback=use_fallback)
    if got == expect:
        _passed += 1
        return True, got
    _failed.append((case, expect, got, "有历史" if history else "无历史"))
    return False, got


def run_group(title, cases, expect, history="", use_fallback=False):
    """跑一组用例并打印对照表"""
    print(f"\n===== {title}（期望 {expect}）=====")
    for case in cases:
        ok, got = check(case, expect, history, use_fallback)
        print(f"  {'[OK]' if ok else '[!!]'} {case!r:<26} -> {got}")


def can_reach_llm():
    """探测"意图兜底"用的小模型能不能调通（决定第 ⑤ 组要不要跑）
    返回：True = 可以跑；False = 跳过（配置关掉了，或断网/欠费）
    【为什么要探测】测试脚本的首要要求是"离线也能跑"。
      答辩现场没网时，前 4 组必须照样全绿；第 ⑤ 组属于"联网增强"，
      连不上就跳过并说明原因，绝不能因此报失败。
    """
    if not config.INTENT_FALLBACK:
        print("\n（.env 里 INTENT_FALLBACK=false，跳过第 ⑤ 组）")
        return False
    try:
        from src.core.agent_service import _get_intent_llm
        _get_intent_llm().invoke("你好")
        return True
    except Exception as error:
        print(f"\n（模型调不通，跳过第 ⑤ 组：{error}）")
        return False


print("=" * 70)
print("意图路由验收测试")
print("=" * 70)

run_group("① 模糊需求 → 应弹问卷", VAGUE_CASES, "vague")
run_group("② 明确需求 → 应直接创作", CREATE_CASES, "create")
run_group("③ 寒暄闲聊 → 应介绍能力", CHITCHAT_CASES, "chitchat")
run_group("④ 追问后 · 又提新需求 → 仍弹问卷", AFTER_ASK_REQUEST, "vague", ASKED_HISTORY)
run_group("④ 追问后 · 在回答问卷 → 直接创作", AFTER_ASK_ANSWER, "create", ASKED_HISTORY)

# ---------------- 第 ⑤ 组：模型兜底（需联网，连不上就跳过） ----------------
_rule_total = _passed + len(_failed)      # 先记下规则层的用例数，便于最后分开报
if can_reach_llm():
    run_group("⑤ 词表外说法 · 模糊 → 兜底应救回", FALLBACK_VAGUE, "vague", "", True)
    run_group("⑤ 词表外说法 · 明确 → 兜底应救回", FALLBACK_CREATE, "create", "", True)
    run_group("⑤ 词表外说法 · 寒暄 → 兜底应救回", FALLBACK_CHITCHAT, "chitchat", "", True)
    run_group("⑤ 词表外说法 · 无关 → 兜底应救回", FALLBACK_OTHER, "other", "", True)

# ---------------- 汇总 ----------------
total = _passed + len(_failed)
print()
print("=" * 70)
print(f"用例总数 {total}｜通过 {_passed}｜失败 {len(_failed)}")
print(f"（其中：规则层 {_rule_total} 条 · 模型兜底层 {total - _rule_total} 条）")
if _failed:
    print("-" * 70)
    print("失败明细（输入 / 期望 / 实际 / 场景）：")
    for case, expect, got, scene in _failed:
        print(f"  {case!r}｜期望 {expect}｜实际 {got}｜{scene}")
    print("=" * 70)
    raise SystemExit(1)
print("全部通过 ✅")
print("=" * 70)
